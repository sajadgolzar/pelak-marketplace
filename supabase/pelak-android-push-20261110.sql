-- PELAK Android native notification foundation (FCM).
-- Run in Supabase SQL Editor AFTER reviewing. Does not change existing web push.
-- This migration stores opaque FCM tokens privately and queues events; real delivery
-- requires an owner-controlled Firebase project, Edge Function, and a cron schedule.
BEGIN;

CREATE TABLE IF NOT EXISTS public.pelak_android_push_tokens (
  token text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pelak_android_push_tokens_by_user
  ON public.pelak_android_push_tokens (user_id,last_seen_at DESC);
ALTER TABLE public.pelak_android_push_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.pelak_android_push_tokens FROM PUBLIC,anon,authenticated;

CREATE TABLE IF NOT EXISTS public.pelak_android_push_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  kind text NOT NULL,
  source_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  attempt_count integer NOT NULL DEFAULT 0,
  last_error text
);
CREATE INDEX IF NOT EXISTS pelak_android_push_outbox_pending
 ON public.pelak_android_push_outbox (created_at)
 WHERE sent_at IS NULL AND attempt_count < 5;
ALTER TABLE public.pelak_android_push_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.pelak_android_push_outbox FROM PUBLIC,anon,authenticated;

-- Authenticated users can register a token only for their own auth.uid.
CREATE OR REPLACE FUNCTION public.pelak_register_android_push(p_token text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Sign in required'; END IF;
  IF p_token IS NULL OR p_token !~ '^[A-Za-z0-9:_-]{40,4096}$' THEN
    RAISE EXCEPTION 'Invalid FCM registration token';
  END IF;
  INSERT INTO public.pelak_android_push_tokens(token,user_id)
  VALUES(p_token,auth.uid())
  ON CONFLICT(token)
  DO UPDATE SET user_id=EXCLUDED.user_id, last_seen_at=now();
  RETURN true;
END;
$$;
REVOKE ALL ON FUNCTION public.pelak_register_android_push(text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.pelak_register_android_push(text)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.pelak_unregister_android_push(p_token text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
DECLARE count_removed integer;
BEGIN
  IF auth.uid() IS NULL THEN RETURN false; END IF;
  DELETE FROM public.pelak_android_push_tokens
  WHERE user_id=auth.uid() AND token=p_token;
  GET DIAGNOSTICS count_removed=ROW_COUNT;
  RETURN count_removed > 0;
END;
$$;
REVOKE ALL ON FUNCTION public.pelak_unregister_android_push(text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.pelak_unregister_android_push(text)
  TO authenticated;

-- Atomic worker claim: no direct client permissions; service role only.
CREATE OR REPLACE FUNCTION public.pelak_android_push_claim(p_limit integer DEFAULT 25)
RETURNS SETOF public.pelak_android_push_outbox
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $$
BEGIN
  RETURN QUERY
  WITH due AS (
    SELECT q.id
    FROM public.pelak_android_push_outbox q
    WHERE q.sent_at IS NULL AND q.attempt_count < 5
      AND (q.claimed_at IS NULL OR q.claimed_at < now() - interval '10 minutes')
    ORDER BY q.created_at ASC
    LIMIT LEAST(GREATEST(COALESCE(p_limit,25),1),50)
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.pelak_android_push_outbox q
  SET claimed_at=now(),attempt_count=q.attempt_count+1
  WHERE q.id IN (SELECT due.id FROM due)
  RETURNING q.*;
END;
$$;
REVOKE ALL ON FUNCTION public.pelak_android_push_claim(integer)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.pelak_android_push_claim(integer) TO service_role;

-- Fan out pre-existing push events to the Android-only outbox.
CREATE OR REPLACE FUNCTION public.pelak_android_enqueue_from_push()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
BEGIN
  IF NEW.recipient_id IS NOT NULL THEN
    INSERT INTO public.pelak_android_push_outbox(recipient_id,kind,source_id)
    VALUES(NEW.recipient_id, LEFT(COALESCE(NEW.kind,'general'),80),NEW.source_id);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS pelak_android_push_event_trigger ON public.pelak_push_events;
CREATE TRIGGER pelak_android_push_event_trigger
 AFTER INSERT ON public.pelak_push_events FOR EACH ROW
 EXECUTE FUNCTION public.pelak_android_enqueue_from_push();

-- Notify the seller when the manager sends an ad back for correction.
CREATE OR REPLACE FUNCTION public.pelak_android_enqueue_revision()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
DECLARE recipient uuid;
BEGIN
  IF NEW.review_state = 'needs_revision'
     AND (TG_OP = 'INSERT' OR OLD.review_state IS DISTINCT FROM 'needs_revision') THEN
    SELECT l.user_id INTO recipient
    FROM public.listings l WHERE l.id=NEW.listing_id;
    IF recipient IS NOT NULL THEN
      INSERT INTO public.pelak_android_push_outbox(recipient_id,kind,source_id)
      VALUES(recipient,'listing_needs_revision',NEW.listing_id);
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS pelak_android_revision_trigger ON public.pelak_listing_rejections;
CREATE TRIGGER pelak_android_revision_trigger
 AFTER INSERT OR UPDATE OF review_state ON public.pelak_listing_rejections
 FOR EACH ROW EXECUTE FUNCTION public.pelak_android_enqueue_revision();

CREATE OR REPLACE FUNCTION public.pelak_android_enqueue_publication()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
BEGIN
  IF NEW.listing_status='published'
     AND OLD.listing_status IS DISTINCT FROM 'published' THEN
    INSERT INTO public.pelak_android_push_outbox(recipient_id,kind,source_id)
    VALUES(NEW.user_id,'listing_published',NEW.id);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS pelak_android_publication_trigger ON public.listings;
CREATE TRIGGER pelak_android_publication_trigger
 AFTER UPDATE OF listing_status ON public.listings FOR EACH ROW
 EXECUTE FUNCTION public.pelak_android_enqueue_publication();

-- Reports are visible only to the existing super_admin; queue a notice.
CREATE OR REPLACE FUNCTION public.pelak_android_enqueue_report()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $$
BEGIN
  INSERT INTO public.pelak_android_push_outbox(recipient_id,kind,source_id)
  SELECT a.user_id,'listing_report',NEW.listing_id
  FROM public.admin_roles a WHERE a.role='super_admin';
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS pelak_android_report_trigger ON public.pelak_listing_reports;
CREATE TRIGGER pelak_android_report_trigger
 AFTER INSERT ON public.pelak_listing_reports FOR EACH ROW
 EXECUTE FUNCTION public.pelak_android_enqueue_report();

COMMIT;
